<script lang="ts">
	import * as Button from "$lib/components/ui/button/index.js";
	import * as Dialog from "$lib/components/ui/dialog/index.js";
	import * as Select from "$lib/components/ui/select/index.js";
	import * as DropdownMenu from "$lib/components/ui/dropdown-menu/index.js";
	import { Badge } from "$lib/components/ui/badge/index.js";
	import { Input } from "$lib/components/ui/input/index.js";
	import { Label } from "$lib/components/ui/label/index.js";
	import { Textarea } from "$lib/components/ui/textarea/index.js";
	import {
		DataTable,
		ConfirmDialog,
		type DataTableColumn,
	} from "$lib/components/common/index.js";
	import { t } from "$lib/i18n/index.js";
	import { cn } from "$lib/utils.js";
	import type { RoleRecord, RoleStatus } from "$lib/types/index.js";
	import { initialRoles } from "$lib/data/role-access-data.js";

	import PlusIcon from "@lucide/svelte/icons/plus";
	import SearchIcon from "@lucide/svelte/icons/search";
	import RotateCcwIcon from "@lucide/svelte/icons/rotate-ccw";
	import ShieldIcon from "@lucide/svelte/icons/shield";
	import UsersIcon from "@lucide/svelte/icons/users";
	import PencilIcon from "@lucide/svelte/icons/pencil";
	import Trash2Icon from "@lucide/svelte/icons/trash-2";
	import KeyRoundIcon from "@lucide/svelte/icons/key-round";
	import EllipsisVerticalIcon from "@lucide/svelte/icons/ellipsis-vertical";
	import CheckCircle2Icon from "@lucide/svelte/icons/check-circle-2";
	import CalendarIcon from "@lucide/svelte/icons/calendar";
	import ShieldAlertIcon from "@lucide/svelte/icons/shield-alert";
	import XIcon from "@lucide/svelte/icons/x";

	// Roles State
	let roles = $state<RoleRecord[]>([...initialRoles]);
	let searchQuery = $state("");
	let statusFilter = $state<string>("all");
	let toastMessage = $state<string | null>(null);

	// Dialog States
	let isCreateOpen = $state(false);
	let isEditOpen = $state(false);
	let isDeleteConfirmOpen = $state(false);
	let roleToEdit = $state<RoleRecord | null>(null);
	let roleToDelete = $state<RoleRecord | null>(null);

	// Form States for Create
	let createName = $state("");
	let createKey = $state("");
	let createDescription = $state("");
	let createStatus = $state<RoleStatus>("active");
	let isKeyAutoGenerated = $state(true);

	// Form States for Edit
	let editName = $state("");
	let editDescription = $state("");
	let editStatus = $state<RoleStatus>("active");

	// Status Filter Options
	const statusFilterOptions = $derived([
		{ value: "all", label: t("user.role.filterStatus") },
		{ value: "active", label: t("user.role.statusActive") },
		{ value: "disable", label: t("user.role.statusDisable") },
	]);

	// Auto-slugify helper for key
	function slugify(text: string): string {
		return text
			.toLowerCase()
			.trim()
			.replace(/[\s\W-]+/g, "_")
			.replace(/^_+|_+$/g, "");
	}

	function handleCreateNameChange(e: Event) {
		const target = e.target as HTMLInputElement;
		createName = target.value;
		if (isKeyAutoGenerated) {
			createKey = slugify(createName);
		}
	}

	function handleCreateKeyInput(e: Event) {
		const target = e.target as HTMLInputElement;
		createKey = slugify(target.value);
		isKeyAutoGenerated = false;
	}

	// Filtered Roles
	const filteredRoles = $derived(
		roles.filter((role) => {
			const query = searchQuery.trim().toLowerCase();
			const matchesQuery =
				!query ||
				role.name.toLowerCase().includes(query) ||
				role.key.toLowerCase().includes(query) ||
				role.description.toLowerCase().includes(query);

			const matchesStatus =
				statusFilter === "all" || role.status === statusFilter;

			return matchesQuery && matchesStatus;
		}),
	);

	// Pagination & Sorting States for DataTable
	let currentPage = $state(1);
	let perPage = $state(10);
	let sortKey = $state<string | null>(null);
	let sortDirection = $state<"asc" | "desc" | "none">("none");

	// Reset page when search or status filter changes
	$effect(() => {
		void searchQuery;
		void statusFilter;
		currentPage = 1;
	});

	function parseDate(dateStr: string): number {
		const parts = dateStr.split("/");
		if (parts.length === 3) {
			const day = parseInt(parts[0], 10);
			const month = parseInt(parts[1], 10) - 1;
			const year = parseInt(parts[2], 10);
			return new Date(year, month, day).getTime();
		}
		return 0;
	}

	// Columns configuration for standard DataTable
	const columns = $derived<DataTableColumn<RoleRecord>[]>([
		{
			id: "name",
			header: t("user.role.colRoleName"),
			sortable: true,
		},
		{
			id: "key",
			header: t("user.role.colKey"),
			sortable: true,
		},
		{
			id: "usersCount",
			header: t("user.role.colUsers"),
			align: "center",
			sortable: true,
		},
		{
			id: "status",
			header: t("user.role.colStatus"),
			align: "center",
			sortable: true,
		},
		{
			id: "createdAt",
			header: t("user.role.colCreatedAt"),
			sortable: true,
			accessorFn: (row: RoleRecord) => parseDate(row.createdAt),
		},
		{
			id: "actions",
			header: t("user.role.colActions"),
			align: "right",
		},
	]);

	function showToast(msg: string) {
		toastMessage = msg;
		setTimeout(() => {
			if (toastMessage === msg) toastMessage = null;
		}, 3500);
	}

	function resetFilters() {
		searchQuery = "";
		statusFilter = "all";
		sortKey = null;
		sortDirection = "none";
		currentPage = 1;
	}

	function openCreateDialog() {
		createName = "";
		createKey = "";
		createDescription = "";
		createStatus = "active";
		isKeyAutoGenerated = true;
		isCreateOpen = true;
	}

	function handleSaveCreate() {
		if (!createName.trim() || !createKey.trim()) return;

		// Check key uniqueness
		if (roles.some((r) => r.key === createKey.trim())) {
			showToast("Role key must be unique.");
			return;
		}

		const today = new Date();
		const dateFormatted = `${String(today.getDate()).padStart(2, "0")}/${String(today.getMonth() + 1).padStart(2, "0")}/${today.getFullYear()}`;

		const newRole: RoleRecord = {
			id: `role-${Date.now()}`,
			name: createName.trim(),
			key: createKey.trim(),
			description: createDescription.trim(),
			usersCount: 0,
			status: createStatus,
			isSystem: false,
			createdAt: dateFormatted,
		};

		roles = [newRole, ...roles];
		isCreateOpen = false;
		showToast(t("user.role.toastCreated"));
	}

	function openEditDialog(role: RoleRecord) {
		roleToEdit = role;
		editName = role.name;
		editDescription = role.description;
		editStatus = role.status;
		isEditOpen = true;
	}

	function handleSaveEdit() {
		if (!roleToEdit || !editName.trim()) return;

		roles = roles.map((r) => {
			if (r.id === roleToEdit?.id) {
				return {
					...r,
					name: editName.trim(),
					description: editDescription.trim(),
					status: editStatus,
					updatedAt: new Date().toISOString(),
				};
			}
			return r;
		});

		isEditOpen = false;
		showToast(t("user.role.toastUpdated"));
	}

	function promptDeleteRole(role: RoleRecord) {
		if (role.isSystem) {
			showToast(t("user.role.cannotDeleteSystemRole"));
			return;
		}
		roleToDelete = role;
		isDeleteConfirmOpen = true;
	}

	function handleConfirmDelete() {
		if (!roleToDelete) return;

		roles = roles.filter((r) => r.id !== roleToDelete?.id);
		isDeleteConfirmOpen = false;
		roleToDelete = null;
		showToast(t("user.role.toastDeleted"));
	}

	function toggleRoleStatus(role: RoleRecord) {
		const newStatus: RoleStatus =
			role.status === "active" ? "disable" : "active";
		roles = roles.map((r) =>
			r.id === role.id ? { ...r, status: newStatus } : r,
		);
		showToast(
			`${role.name} ${t("user.manage.statusChangedTo")} ${newStatus === "active" ? t("user.role.statusActive") : t("user.role.statusDisable")}`,
		);
	}
</script>

<svelte:head>
	<title>{t("user.role.title")} | OmniFlow</title>
</svelte:head>

<!-- Toast Notification -->
{#if toastMessage}
	<div
		class="fixed bottom-5 right-5 z-50 flex items-center gap-2 rounded-xl bg-foreground px-4 py-3 text-xs font-semibold text-background shadow-xl animate-in slide-in-from-bottom-5 duration-200"
	>
		<CheckCircle2Icon class="size-4 text-emerald-400" />
		<span>{toastMessage}</span>
	</div>
{/if}

<div class="space-y-6">
	<!-- Page Header -->
	<div
		class="flex flex-col sm:flex-row sm:items-center justify-between gap-4 pb-2 border-b border-border/60"
	>
		<div>
			<h1
				class="font-heading text-2xl font-bold tracking-tight text-foreground flex items-center gap-2"
			>
				<ShieldIcon class="size-6 text-primary" />
				<span>{t("user.role.title")}</span>
			</h1>
			<p class="text-xs text-muted-foreground mt-1">
				{t("user.role.subtitle")}
			</p>
		</div>

		<div class="flex items-center gap-3">
			<Button.Root
				type="button"
				onclick={openCreateDialog}
				class="h-9 px-4 text-xs font-semibold bg-primary text-primary-foreground hover:bg-primary/90 cursor-pointer flex items-center gap-2 shadow-xs shrink-0"
			>
				<PlusIcon class="size-4" />
				<span>{t("user.role.createBtn")}</span>
			</Button.Root>
		</div>
	</div>

	<!-- Search & Filters Container (full width) -->
	<div class="w-full space-y-3">
		<div class="flex flex-col gap-3 lg:flex-row lg:items-center">
			<!-- Search Column - full width -->
			<div class="relative flex-1">
				<SearchIcon
					class="pointer-events-none absolute left-3.5 top-1/2 size-4 -translate-y-1/2 text-muted-foreground z-10"
				/>
				<Input
					type="text"
					role="searchbox"
					bind:value={searchQuery}
					placeholder={t("user.role.searchPlaceholder")}
					class="h-10 w-full rounded-lg border border-border/80 bg-white dark:bg-card pl-10 pr-9 text-xs sm:text-sm text-foreground placeholder:text-muted-foreground/70 focus:border-primary focus:outline-hidden focus:ring-1 focus:ring-primary focus-visible:border-primary focus-visible:ring-1 focus-visible:ring-primary shadow-xs transition-all [&::-webkit-search-cancel-button]:hidden [&::-webkit-search-decoration]:hidden"
				/>
				{#if searchQuery}
					<button
						type="button"
						onclick={() => (searchQuery = "")}
						class="absolute right-3 top-1/2 -translate-y-1/2 text-muted-foreground hover:text-foreground cursor-pointer"
						aria-label="Clear search"
					>
						<XIcon class="size-4" />
					</button>
				{/if}
			</div>

			<!-- Status Filter -->
			<div class="w-full sm:w-56">
				<Select.Root
					type="single"
					bind:value={statusFilter}
					items={statusFilterOptions}
				>
					<Select.Trigger
						class="h-10 w-full rounded-lg border border-border bg-white dark:bg-card px-3 text-xs font-medium text-foreground shadow-xs cursor-pointer hover:border-primary/50 hover:bg-slate-50 dark:hover:bg-muted/60 transition-colors"
					>
						<Select.Value
							placeholder={t("user.role.filterStatus")}
						/>
					</Select.Trigger>
					<Select.Content>
						{#each statusFilterOptions as opt}
							<Select.Item
								value={opt.value}
								label={opt.label}
							>
								{opt.label}
							</Select.Item>
						{/each}
					</Select.Content>
				</Select.Root>
			</div>

			<!-- Reset Button -->
			<Button.Root
				variant="outline"
				onclick={resetFilters}
				class="h-10 gap-1.5 rounded-lg border border-border bg-white dark:bg-card px-3.5 text-xs font-semibold text-foreground hover:bg-slate-50 dark:hover:bg-muted hover:text-foreground shadow-xs cursor-pointer shrink-0 transition-colors group/reset"
				title="Reset all filters"
			>
				<RotateCcwIcon
					class="size-3.5 text-muted-foreground group-hover/reset:text-foreground transition-colors"
				/>
				<span>{t("user.role.reset")}</span>
			</Button.Root>
		</div>
	</div>

	<!-- Roles DataTable with Built-in Sorting & Pagination -->
	<DataTable
		data={filteredRoles}
		{columns}
		bind:page={currentPage}
		bind:perPage
		perPageOptions={[10, 20, 50, 100]}
		bind:sortKey
		bind:sortDirection
		emptyMessage={t("user.role.emptyState")}
		emptyIcon={ShieldAlertIcon}
	>
		{#snippet cell({
			item,
			column,
		}: {
			item: RoleRecord;
			column: DataTableColumn<RoleRecord>;
		})}
			{#if column.id === "name"}
				<div class="flex items-center gap-2.5">
					<div
						class={cn(
							"size-8 rounded-lg flex items-center justify-center shrink-0 text-xs font-bold",
							item.isSystem
								? "bg-primary/10 text-primary border border-primary/20"
								: "bg-muted text-muted-foreground border border-border",
						)}
					>
						{item.name.charAt(0)}
					</div>
					<div class="flex flex-col">
						<div class="flex items-center gap-2">
							<span class="text-xs font-semibold text-foreground">
								{item.name}
							</span>
							{#if item.isSystem}
								<Badge
									variant="secondary"
									class="text-[10px] px-1.5 py-0 h-4 font-medium bg-primary/10 text-primary border-primary/20"
								>
									{t("user.role.badgeSystem")}
								</Badge>
							{:else}
								<Badge
									variant="outline"
									class="text-[10px] px-1.5 py-0 h-4 font-normal text-muted-foreground"
								>
									{t("user.role.badgeCustom")}
								</Badge>
							{/if}
						</div>
					</div>
				</div>
			{:else if column.id === "key"}
				<code
					class="rounded bg-muted/80 px-2 py-0.5 text-[11px] font-mono text-muted-foreground border border-border/50"
				>
					{item.key}
				</code>
			{:else if column.id === "usersCount"}
				<Badge
					variant="outline"
					class="text-xs font-medium px-2 py-0.5 inline-flex items-center gap-1 bg-background"
				>
					<UsersIcon class="size-3 text-muted-foreground" />
					<span>{item.usersCount}</span>
				</Badge>
			{:else if column.id === "status"}
				<button
					type="button"
					onclick={() => toggleRoleStatus(item)}
					class="cursor-pointer inline-flex items-center"
					title="Toggle status"
				>
					{#if item.status === "active"}
						<Badge
							class="bg-emerald-500/15 text-emerald-700 dark:text-emerald-400 hover:bg-emerald-500/25 border-emerald-500/30 text-[11px] font-medium transition-colors"
						>
							<span
								class="size-1.5 rounded-full bg-emerald-500 mr-1 animate-pulse"
							></span>
							{t("user.role.statusActive")}
						</Badge>
					{:else}
						<Badge
							variant="secondary"
							class="bg-muted text-muted-foreground text-[11px] font-medium"
						>
							<span
								class="size-1.5 rounded-full bg-muted-foreground/60 mr-1"
							></span>
							{t("user.role.statusDisable")}
						</Badge>
					{/if}
				</button>
			{:else if column.id === "createdAt"}
				<div
					class="flex items-center gap-1.5 text-xs text-muted-foreground"
				>
					<CalendarIcon class="size-3 text-muted-foreground/70" />
					<span>{item.createdAt}</span>
				</div>
			{:else if column.id === "actions"}
				<div class="flex items-center justify-end gap-1.5">
					<!-- More Options Dropdown -->
					<DropdownMenu.Root>
						<DropdownMenu.Trigger
							class="inline-flex size-8 items-center justify-center rounded-md border border-border bg-background hover:bg-muted text-muted-foreground hover:text-foreground transition-colors cursor-pointer"
						>
							<EllipsisVerticalIcon class="size-4" />
						</DropdownMenu.Trigger>
						<DropdownMenu.Content align="end" class="w-44">
							<DropdownMenu.Item
								onclick={() => openEditDialog(item)}
								class="cursor-pointer text-xs"
							>
								<PencilIcon class="mr-2 size-3.5" />
								<span>{t("user.role.actionEdit")}</span>
							</DropdownMenu.Item>

							<DropdownMenu.Item class="cursor-pointer text-xs">
								<a
									href={`/user/access?role=${item.key}`}
									class="flex items-center w-full"
								>
									<KeyRoundIcon
										class="mr-2 size-3.5 text-primary"
									/>
									<span
										>{t(
											"user.role.actionManageAccess",
										)}</span
									>
								</a>
							</DropdownMenu.Item>

							<DropdownMenu.Separator />

							{#if item.isSystem}
								<DropdownMenu.Item
									disabled
									class="text-xs text-muted-foreground/50 cursor-not-allowed"
								>
									<Trash2Icon class="mr-2 size-3.5" />
									<span
										>{t("user.role.actionDelete")} (System)</span
									>
								</DropdownMenu.Item>
							{:else}
								<DropdownMenu.Item
									onclick={() => promptDeleteRole(item)}
									class="cursor-pointer text-xs text-destructive focus:text-destructive"
								>
									<Trash2Icon class="mr-2 size-3.5" />
									<span>{t("user.role.actionDelete")}</span>
								</DropdownMenu.Item>
							{/if}
						</DropdownMenu.Content>
					</DropdownMenu.Root>
				</div>
			{/if}
		{/snippet}
	</DataTable>
</div>

<!-- CREATE ROLE DIALOG -->
<Dialog.Root bind:open={isCreateOpen}>
	<Dialog.Content class="sm:max-w-md">
		<Dialog.Header>
			<Dialog.Title class="text-base font-bold flex items-center gap-2">
				<ShieldIcon class="size-5 text-primary" />
				<span>{t("user.role.createRoleTitle")}</span>
			</Dialog.Title>
			<Dialog.Description class="text-xs text-muted-foreground">
				{t("user.role.createRoleDesc")}
			</Dialog.Description>
		</Dialog.Header>

		<div class="space-y-4 py-2">
			<!-- Role Name -->
			<div class="space-y-1.5">
				<Label class="text-xs font-semibold"
					>{t("user.role.roleNameLabel")} *</Label
				>
				<Input
					type="text"
					value={createName}
					oninput={handleCreateNameChange}
					placeholder="e.g. Warehouse Supervisor"
					class="h-9 text-xs"
				/>
			</div>

			<!-- Role Key -->
			<div class="space-y-1.5">
				<div class="flex items-center justify-between">
					<Label class="text-xs font-semibold"
						>{t("user.role.roleKeyLabel")} *</Label
					>
					<span class="text-[10px] text-muted-foreground">
						{isKeyAutoGenerated ? "Auto-generated" : "Custom key"}
					</span>
				</div>
				<Input
					type="text"
					value={createKey}
					oninput={handleCreateKeyInput}
					placeholder="warehouse_supervisor"
					class="h-9 text-xs font-mono"
				/>
				<p class="text-[11px] text-muted-foreground leading-tight">
					{t("user.role.roleKeyHelp")}
				</p>
			</div>

			<!-- Description -->
			<div class="space-y-1.5">
				<Label class="text-xs font-semibold"
					>{t("user.role.descriptionLabel")}</Label
				>
				<Textarea
					bind:value={createDescription}
					placeholder="Describe the operational responsibilities of this role..."
					rows={3}
					class="text-xs resize-none"
				/>
			</div>

			<!-- Status -->
			<div class="space-y-1.5">
				<Label class="text-xs font-semibold"
					>{t("user.role.statusLabel")}</Label
				>
				<Select.Root
					type="single"
					bind:value={createStatus}
					items={[
						{ value: "active", label: t("user.role.statusActive") },
						{
							value: "disable",
							label: t("user.role.statusDisable"),
						},
					]}
				>
					<Select.Trigger class="h-9 text-xs">
						<Select.Value />
					</Select.Trigger>
					<Select.Content>
						<Select.Item
							value="active"
							label={t("user.role.statusActive")}
						>
							{t("user.role.statusActive")}
						</Select.Item>
						<Select.Item
							value="disable"
							label={t("user.role.statusDisable")}
						>
							{t("user.role.statusDisable")}
						</Select.Item>
					</Select.Content>
				</Select.Root>
			</div>
		</div>

		<Dialog.Footer class="flex sm:justify-end gap-2 pt-2">
			<Button.Root
				type="button"
				variant="outline"
				onclick={() => (isCreateOpen = false)}
				class="h-9 text-xs"
			>
				{t("common.cancel")}
			</Button.Root>
			<Button.Root
				type="button"
				onclick={handleSaveCreate}
				disabled={!createName.trim() || !createKey.trim()}
				class="h-9 text-xs bg-primary text-primary-foreground hover:bg-primary/90"
			>
				{t("user.role.createBtn")}
			</Button.Root>
		</Dialog.Footer>
	</Dialog.Content>
</Dialog.Root>

<!-- EDIT ROLE DIALOG -->
<Dialog.Root bind:open={isEditOpen}>
	<Dialog.Content class="sm:max-w-md">
		<Dialog.Header>
			<Dialog.Title class="text-base font-bold flex items-center gap-2">
				<PencilIcon class="size-5 text-primary" />
				<span>{t("user.role.editRoleTitle")}</span>
			</Dialog.Title>
			<Dialog.Description class="text-xs text-muted-foreground">
				{t("user.role.editRoleDesc")}
			</Dialog.Description>
		</Dialog.Header>

		<div class="space-y-4 py-2">
			<!-- Role Name -->
			<div class="space-y-1.5">
				<Label class="text-xs font-semibold"
					>{t("user.role.roleNameLabel")} *</Label
				>
				<Input
					type="text"
					bind:value={editName}
					placeholder="e.g. Warehouse Supervisor"
					class="h-9 text-xs"
				/>
			</div>

